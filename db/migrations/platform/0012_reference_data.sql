-- Reference data (P2-1, docs/27 §3.11): vehicle makes and models, managed by platform staff and
-- read by every tenant. (Tax codes and rates belong to each business, decision 100.)

create table vehicle_makes (
  id      uuid primary key default uuidv7(),
  name    citext not null unique check (length(trim(name)) between 1 and 60),
  sort    integer not null default 0,
  active  boolean not null default true
);

create table vehicle_models (
  id       uuid primary key default uuidv7(),
  make_id  uuid not null references vehicle_makes (id),
  name     citext not null check (length(trim(name)) between 1 and 60),
  sort     integer not null default 0,
  active   boolean not null default true,
  unique (make_id, name)
);

