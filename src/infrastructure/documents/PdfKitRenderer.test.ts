import { describe, expect, it } from "vitest";
import type { PdfDocument } from "../../application/ports/IPdfRenderer.js";
import { PdfKitRenderer } from "./PdfKitRenderer.js";

const pages = (pdf: Buffer) => (pdf.toString("latin1").match(/\/Type \/Page\b/g) ?? []).length;

const statement = (lines: number): PdfDocument => ({
  title: "Driver statement",
  reference: "2026-10-01 to 2026-10-20",
  issuer: { name: "Accra Fleet Ltd", lines: ["TIN C0001234567", "+233 24 000 0000"], logo: null },
  blocks: [
    { type: "fields", rows: [{ label: "Driver", value: "Kwame Mensah (DRV-0001)" }] },
    { type: "amount", label: "Closing balance", value: "GHS 500.00" },
    {
      type: "table",
      columns: [
        { header: "Date", width: 0.2 },
        { header: "Description", width: 0.5 },
        { header: "Amount", width: 0.3, align: "right" },
      ],
      rows: Array.from({ length: lines }, (_, i) => ["2026-10-01", `Line ${i}`, "GHS 250.00"]),
      total: ["", "Total", "GHS 1.00"],
    },
  ],
  footer: "Generated by Autoforce Manager",
  createdAt: new Date("2026-10-20T10:00:00Z"),
});

describe("PdfKitRenderer", () => {
  const renderer = new PdfKitRenderer();

  it("renders A4 pages and continues long tables on new pages", async () => {
    const short = await renderer.render(statement(3));
    expect(short.subarray(0, 5).toString()).toBe("%PDF-");
    expect(pages(short)).toBe(1);
    expect(pages(await renderer.render({ ...statement(120), watermark: "VOID" }))).toBeGreaterThan(
      2,
    );
  });

  it("gives the same bytes for the same document", async () => {
    expect((await renderer.render(statement(5))).equals(await renderer.render(statement(5)))).toBe(
      true,
    );
  });

  it("ignores a logo it cannot read", async () => {
    const pdf = await renderer.render({
      ...statement(1),
      issuer: { name: "X", lines: [], logo: new Uint8Array([0x89, 0x50, 0x4e, 0x47, 1, 2, 3]) },
    });
    expect(pages(pdf)).toBe(1);
  });
});
